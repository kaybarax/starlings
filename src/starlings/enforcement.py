"""Authority-side enforcement hook for staging and release refs.

``starlings authority protect`` installs a deterministic generated script
as both the ``update`` and ``reference-transaction`` hooks of a local bare
authority, and records the script's sha256 and the protected ref set in the
state database. The hook calls back into ``starlings authority
check-intent`` for every ref update: a write to a recorded staging or
release ref is allowed only when the journal holds a matching promotion
intent (state ``intent``, or ``landed`` for an exact replay) or a prepared
staging candidate for the same ref, old and new values. Every other ref
passes. ``starlings promote`` and ungated ``stage`` run their authority ref
writes with hooks enabled on a protected authority, so the hook verifies
the intent the CLI journaled before the write.

This guards protected refs against drift and accidental direct writes: a
raw ``git push`` or ``git update-ref`` to a staging or release branch that
matches no recorded intent is refused. It is not credential separation —
anyone who can edit or delete the hook files, or run git with hooks
disabled, bypasses it.
"""

import hashlib
import json
import os
from pathlib import Path
import sqlite3
import stat
import sys

from . import gitops
from .batches import Failure, check_object, default_owner, invalid
from .store import LeaseHeld, LeaseLost, RequestConflict
from .verifier import authority_path, current_trust, trusted_policy

HOOK_NAMES = ("update", "reference-transaction")


def literal(value, label):
    if type(value) is not str or not value or any(c in value for c in ("'", "\n", "\r")):
        raise invalid(f"{label}: paths and values baked into the enforcement hook must be nonempty and contain no quotes or newlines")
    return "'" + value + "'"


def hook_script(state_dir, authority):
    lines = [
        "#!/bin/sh",
        "# Generated by starlings authority protect. Deterministic content; do not edit.",
        "# Refuses updates to recorded staging/release refs that match no",
        "# journaled promotion intent or prepared staging candidate.",
        "STARPYTHON=" + literal(sys.executable or "python3", "python"),
        "STARPYPATH=" + literal(str(Path(__file__).resolve().parent.parent), "starlings package"),
        "STARSTATE=" + literal(str(state_dir), "state directory"),
        "STARAUTH=" + literal(str(authority), "authority"),
        'export PYTHONPATH="$STARPYPATH${PYTHONPATH:+:$PYTHONPATH}"',
        'check() { "$STARPYTHON" -m starlings authority check-intent --state-dir "$STARSTATE" --authority "$STARAUTH" -- "$1" "$2" "$3" >/dev/null; }',
        'if [ "$#" -eq 1 ]; then',
        '    case "$1" in',
        "        preparing|prepared)",
        "            STATUS=0",
        '            while IFS=" " read -r OLD NEW REF; do',
        '                check "$REF" "$OLD" "$NEW" || STATUS=1',
        "            done",
        '            exit "$STATUS"',
        "            ;;",
        "    esac",
        "    exit 0",
        "fi",
        'check "$1" "$2" "$3"',
        "",
    ]
    return "\n".join(lines)


def hook_digest(script):
    return hashlib.sha256(script.encode("utf-8")).hexdigest()


def install_hook(path, script):
    data = script.encode("utf-8")
    if path.is_symlink():
        raise Failure("conflict", "hook-exists", f"refusing to replace the symlinked hook {path}")
    if path.exists():
        if path.is_file() and path.read_bytes() == data:
            os.chmod(path, 0o755)
            return "already-installed"
        raise Failure("conflict", "hook-exists", f"{path} exists with different content; inspect it and remove it before running authority protect again")
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    descriptor = os.open(temporary, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o755)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary, path)
        os.chmod(path, 0o755)
    finally:
        if temporary.exists():
            temporary.unlink()
    return "installed"


def protected_refs(ctx, authority):
    c = ctx.store.connection
    trusted = current_trust(c, str(authority))
    if trusted is not None:
        policy = trusted_policy(ctx, trusted["digest"])
        return sorted({"refs/heads/" + policy["staging"], "refs/heads/" + policy["release"]})
    branches = set()
    for row in c.execute("SELECT staging, release FROM batches WHERE authority = ?", (str(authority),)).fetchall():
        branches.update(("refs/heads/" + row["staging"], "refs/heads/" + row["release"]))
    if not branches:
        raise invalid(f"no trusted policy or batch records name staging and release branches for {authority}; trust a policy or prepare a batch before protecting it")
    return sorted(branches)


def protect(ctx, authority, owner=None, seconds=600):
    owner = owner or default_owner()
    authority = authority_path(authority)
    refs = protected_refs(ctx, authority)
    script = hook_script(ctx.root, authority)
    digest = hook_digest(script)
    leases = []
    try:
        for ref in refs:
            leases.append(ctx.store.acquire(f"target:{authority}:{ref}", owner, seconds))
    except LeaseHeld as exc:
        for lease in leases:
            try:
                ctx.store.release(lease)
            except LeaseLost:
                pass
        raise Failure("blocked", "lease-held", f"{exc}; authority protect waits for the promotion or staging holding it; retry") from exc
    result = {"authority": str(authority), "hook_sha256": digest, "protected_refs": refs}
    try:
        with ctx.store.transaction() as tx:
            for lease in leases:
                ctx.store.check(tx, lease)
            try:
                repeated = ctx.store.request(tx, "authority-protect", str(authority), {"hook_sha256": digest, "protected_refs": refs})
            except RequestConflict as exc:
                raise Failure("conflict", "conflict", f"{authority} is already recorded as protected with a different hook or ref set; {exc}") from exc
            if not repeated:
                tx.execute("INSERT OR REPLACE INTO authorities(authority, hook_sha256, protected_refs, installed_at) VALUES (?, ?, ?, ?)", (str(authority), digest, json.dumps(refs, sort_keys=True), ctx.store.clock()))
        hooks = authority / "hooks"
        if not hooks.is_dir():
            raise invalid(f"authority has no hooks directory: {hooks}")
        result["hooks"] = {name: install_hook(hooks / name, script) for name in HOOK_NAMES}
        result["repeated"] = repeated
        result["recorded"] = True
    except LeaseLost as exc:
        raise Failure("stale", "lease-lost", str(exc)) from exc
    finally:
        for lease in leases:
            try:
                ctx.store.release(lease)
            except LeaseLost:
                result["lease_released"] = False
    return "ok", result


def hook_files_state(authority, hook_sha256):
    per_file = {}
    for name in HOOK_NAMES:
        path = Path(authority) / "hooks" / name
        if path.is_symlink() or (path.exists() and not path.is_file()):
            per_file[name] = "modified"
        elif not path.exists():
            per_file[name] = "missing"
        elif hashlib.sha256(path.read_bytes()).hexdigest() != hook_sha256 or not stat.S_IMODE(path.stat().st_mode) & 0o111:
            per_file[name] = "modified"
        else:
            per_file[name] = "installed"
    overall = "installed" if all(value == "installed" for value in per_file.values()) else "missing" if all(value == "missing" for value in per_file.values()) else "modified"
    return overall, per_file


def protection_record(c, repository):
    return c.execute("SELECT hook_sha256, protected_refs, installed_at FROM authorities WHERE authority = ?", (str(repository),)).fetchone()


def hook_guard(c, repository, allow_unprotected=False):
    """Decide whether ref writes to ``repository`` must run the recorded hook.

    Returns True when the repository is recorded as protected and its hook
    files are installed and unmodified. A recorded authority whose hook is
    missing or modified blocks protected ref writes unless the caller passed
    ``--allow-unprotected``, in which case the write runs with hooks off.
    """
    row = protection_record(c, repository)
    if row is None:
        return False
    overall, per_file = hook_files_state(repository, row["hook_sha256"])
    if overall == "installed":
        return True
    if allow_unprotected:
        return False
    raise Failure("blocked", "unprotected-authority", f"{repository} is recorded as hook-protected but its enforcement hook is {overall} ({', '.join(f'{k}: {v}' for k, v in per_file.items())}); reinstall it with starlings authority protect --authority {repository} or pass --allow-unprotected to proceed without enforcement", {"authority": str(repository), "hook": overall, "hooks": per_file, "allowed_with": "--allow-unprotected"})


def read_only(state_dir):
    db = Path(state_dir) / "starlings.db"
    try:
        conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=30)
    except sqlite3.Error as exc:
        raise Failure("blocked", "ref-update-refused", f"cannot read the starlings state database {db}; refusing the update: {exc}") from exc
    conn.row_factory = sqlite3.Row
    return conn


def check_intent(state_dir, authority, refname, old, new):
    if type(refname) is not str or not refname.startswith("refs/") or any(ord(c) < 32 for c in refname):
        raise invalid("refname: expected a fully qualified ref")
    check_object(old, "old")
    check_object(new, "new")
    if state_dir is None:
        raise invalid("--state-dir or STARLINGS_STATE_DIR is required")
    authority_text = str(Path(authority).resolve())
    conn = read_only(state_dir)
    try:
        try:
            row = conn.execute("SELECT protected_refs FROM authorities WHERE authority = ?", (authority_text,)).fetchone()
        except sqlite3.Error as exc:
            raise Failure("blocked", "ref-update-refused", f"the protection record for {authority_text} is unreadable; refusing the update of {refname}: {exc}") from exc
        if row is None:
            raise Failure("blocked", "ref-update-refused", f"no protection record for authority {authority_text}; refusing the update of {refname}")
        protected = json.loads(row["protected_refs"])
        if refname not in protected:
            return "ok", {"allowed": True, "ref": refname, "protected": False}
        if set(new) == {"0"}:
            # A `verify` line in an `update-ref --stdin` transaction is reported
            # to the reference-transaction hook as <old> <zeros> <ref>, identical
            # in shape to a deletion. Allow it when a journaled intent names this
            # ref and old value among its recorded sources (a promote verifies
            # its staging source inside the same atomic transaction).
            for pending in conn.execute("SELECT id, sources FROM promotions WHERE repository = ? AND state IN ('intent', 'landed')", (authority_text,)).fetchall():
                if json.loads(pending["sources"]).get(refname) == old:
                    return "ok", {"allowed": True, "ref": refname, "protected": True, "intent": pending["id"], "verify_only": True}
            raise Failure("blocked", "ref-update-refused", f"{refname} is a protected ref of {authority_text}; deleting or moving it requires a promotion intent journaled by starlings promote or stage; refusing {old} -> {new}", {"ref": refname, "old": old, "new": new, "authority": authority_text})
        intent = conn.execute("SELECT id FROM promotions WHERE repository = ? AND target = ? AND old = ? AND new = ? AND state IN ('intent', 'landed') LIMIT 1", (authority_text, refname, old, new)).fetchone()
        if intent is not None:
            return "ok", {"allowed": True, "ref": refname, "protected": True, "intent": intent["id"]}
        for candidate in conn.execute("SELECT record FROM candidates WHERE commit_sha = ? AND state IN ('prepared', 'staged')", (new,)).fetchall():
            record = json.loads(candidate["record"])
            if record.get("authority") == authority_text and record.get("target") == refname and record.get("base") == old:
                return "ok", {"allowed": True, "ref": refname, "protected": True, "intent": "staging candidate " + record["id"]}
    finally:
        conn.close()
    raise Failure("blocked", "ref-update-refused", f"{refname} is a protected ref of {authority_text}; updates to it require a promotion intent journaled by starlings promote or stage; refusing {old} -> {new}", {"ref": refname, "old": old, "new": new, "authority": authority_text})


def probe(state_dir, authority):
    result = {"authority": str(authority) if authority is not None else None, "probed": authority is not None, "bare": None, "recorded": False, "protected_refs": [], "hook_sha256": None, "hooks": {}, "installed": False, "unmodified": False, "implemented": False, "mode": "coordinator-enforced"}
    if authority is None:
        return result
    path = Path(authority)
    if not path.is_dir() or not gitops.is_bare(path):
        return result
    resolved = str(path.resolve())
    result["authority"] = resolved
    result["bare"] = True
    if state_dir is None or not (Path(state_dir) / "starlings.db").is_file():
        return result
    try:
        conn = read_only(state_dir)
    except Failure as exc:
        result["state_error"] = exc.message
        return result
    try:
        try:
            row = conn.execute("SELECT hook_sha256, protected_refs FROM authorities WHERE authority = ?", (resolved,)).fetchone()
        except sqlite3.Error:
            row = None
    finally:
        conn.close()
    if row is None:
        return result
    refs = json.loads(row["protected_refs"])
    overall, per_file = hook_files_state(path, row["hook_sha256"])
    result.update({"recorded": True, "protected_refs": refs, "hook_sha256": row["hook_sha256"], "hooks": per_file, "installed": all(value != "missing" for value in per_file.values()), "unmodified": overall == "installed", "implemented": overall == "installed" and bool(refs), "mode": "hook-enforced" if overall == "installed" and refs else "coordinator-enforced"})
    return result
